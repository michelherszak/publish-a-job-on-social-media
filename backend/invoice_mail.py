"""Retryable delivery of links to Stripe's finalized invoice PDFs.

The PDF is generated by Stripe. This module never creates an accounting document.
"""
import os
import re
import time
from urllib.parse import urlparse

from fastapi import HTTPException

from . import mail_templates


def schema(conn):
    conn.execute("""CREATE TABLE IF NOT EXISTS invoice_deliveries (
        invoice_id TEXT PRIMARY KEY,
        source_id TEXT NOT NULL UNIQUE,
        organization_id INTEGER NOT NULL REFERENCES organizations(id),
        customer TEXT NOT NULL,
        recipient TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'pending',
        created_at INTEGER NOT NULL,
        sent_at INTEGER
    )""")


def queue(conn, org, customer, invoice_id, source_id):
    if not isinstance(invoice_id, str) or not re.fullmatch(r"in_[A-Za-z0-9_]+", invoice_id):
        raise HTTPException(409, "Bezahlte Stripe-Rechnung fehlt; Ereignis erneut zustellen.")
    recipient = conn.execute(
        "SELECT email FROM users WHERE organization_id=? AND role='firmen_admin' "
        "AND email_verified=1 ORDER BY id LIMIT 1", (org,)
    ).fetchone()
    if not recipient:
        raise HTTPException(409, "Kein bestätigter Rechnungsempfänger vorhanden.")
    conn.execute(
        "INSERT OR IGNORE INTO invoice_deliveries "
        "(invoice_id,source_id,organization_id,customer,recipient,created_at) VALUES(?,?,?,?,?,?)",
        (invoice_id, source_id, org, customer, recipient[0], int(time.time()))
    )


def deliver(db, source_id):
    """Deliver after the payment transaction commits; webhook retries pending mail."""
    from . import auth, billing
    with db() as conn:
        row = conn.execute("SELECT * FROM invoice_deliveries WHERE source_id=?", (source_id,)).fetchone()
        recipient = conn.execute("SELECT email_language FROM users WHERE email=? AND organization_id=?", (row["recipient"], row["organization_id"])).fetchone() if row else None
    if not row or row["status"] == "sent":
        return
    if billing.configuration()["mode"] == "live" and os.getenv("MH_INVOICE_READY") != "1":
        raise HTTPException(503, "Rechnungsangaben sind noch nicht freigegeben.")
    invoice = billing.remote("invoices", row["invoice_id"])
    if (invoice.get("status") != "paid" or invoice.get("paid_out_of_band")
            or billing.object_id(invoice.get("customer")) != row["customer"]
            or invoice.get("currency") != "eur"
            or ((invoice.get("customer_address") or {}).get("country") not in billing.EU)):
        raise HTTPException(409, "Rechnung muss vor Versand geprüft werden.")
    pdf = invoice.get("invoice_pdf") or ""
    parsed = urlparse(pdf)
    if (parsed.scheme != "https" or parsed.hostname not in {"pay.stripe.com", "invoice.stripe.com"}
            or parsed.username or parsed.password or not parsed.path):
        raise HTTPException(503, "Stripe-Rechnungs-PDF ist noch nicht verfügbar.")
    number = invoice.get("number") or row["invoice_id"]
    if not re.fullmatch(r"[A-Za-z0-9_-]{1,80}", number):
        number = row["invoice_id"]
    message = mail_templates.invoice_message(
        os.getenv("MH_MAIL_FROM", "MH <noreply@mh.local>"), row["recipient"], number, pdf, recipient["email_language"] if recipient else "de")
    auth.deliver_message(message)
    with db() as conn:
        conn.execute("UPDATE invoice_deliveries SET status='sent',sent_at=? "
                     "WHERE invoice_id=? AND status='pending'", (int(time.time()), row["invoice_id"]))
